# -*- coding: utf-8 -*-
"""اصلاح اصطلاحات seed.ts طبق راهنمای واژگان (docs/TRANSLATION-GUIDE.md)
قاعده: نام کلاس‌ها/نژادها = اصطلاح رایج جامعه گیمری ایران، نه ترجمه رسمی."""
import io, re

p = 'scripts/seed.ts'
s = io.open(p, encoding='utf-8').read()
orig_len = len(s)
n_repl = 0

def rep(old, new, count=None):
    global s, n_repl
    c = s.count(old)
    if count is not None and c != count:
        print(f"⚠ count mismatch for {old!r}: expected {count}, got {c}")
    s = s.replace(old, new)
    n_repl += c
    print(f"  {c:3d} × {old}  →  {new}")

# --- نام‌های خاص بی‌خطر (جایگزینی کامل) ---
rep('شکارچی اهریمن', 'دی‌اچ')
rep('شوالیه مرگ', 'دث‌نایت')
rep('واریر', 'واریور')            # واریرها هم خودکار درست می‌شود
rep('وارلوک', 'وارلاک')
rep('مانک', 'مونک')
rep('درنایی', 'درانئی')           # درنایی‌ها → درانئی‌ها
rep('آندد', 'آندید')              # آنددها → آندیدها
rep('بلاد الف', 'بلادالف')
rep('هیولر', 'هیلر')
rep('اهرمن', 'اهریمن')            # تایپوی قدیمی
rep('نبیاتا', 'نارو')             # دروید نژاد درانئی
rep('فارسیت‌ها', 'فورسوکن‌ها')     # Forsaken

# --- واژه‌های خطرناک با مرز کلمه (راب در «برابر»، مگ در «خشمگین»، پرست در «نورپرستی») ---
FA = r'\u0600-\u06FF'
rep('پرستشان', 'پریست‌شان')
for term, new in [('راب', 'روگ'), ('پرست', 'پریست'), ('مگ', 'مج')]:
    pat = re.compile(rf'(?<![{FA}]){term}(?![{FA}])')
    s, c = pat.subn(new, s)
    n_repl += c
    print(f"  {c:3d} × {term} (مرزبندی‌شده)  →  {new}")

# --- اصطلاحات شاخه‌های کلاس به لحن گیمری ---
rep('سه شاخه اصلی: اسلحه، فیوری و سلاح‌ورزی', 'سه شاخه اصلی: آرمز، فیوری و پروت')
rep('دو شاخه: ستیز و ویرانی', 'دو شاخه: هیوک و ونجنس')
rep('شکارچیان دژپوش که برای نبرد', 'دی‌اچ‌ها که برای نبرد')

io.open(p, 'w', encoding='utf-8').write(s)
print(f"\n✓ {n_repl} جایگزینی ({orig_len} → {len(s)} کاراکتر)")

# اعتبارسنجی: نباید واریر/راب قدیمی بماید
for bad in ['واریر', '"راب"', '"پرست"', '"مگ"', 'شوالیه مرگ', 'مانک', 'درنایی', '"آندد"', 'بلاد الف', 'هیولر']:
    if bad in s:
        print(f"✗ هنوز باقی مانده: {bad}")
print("اعتبارسنجی تمام")
